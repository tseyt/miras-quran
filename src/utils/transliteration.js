export function transliterate(text, lang) {
    if (!text) return text;
    const map = lang === 'ru' ? RU_MAP : (lang === 'ua' ? UA_MAP : null);
    if (!map) return text;

    return text.split('').map(char => map[char] || char).join('');
}
